#!/usr/bin/env python3
"""Generate Kotlin R classes, string tables and the drawable-path table from Android resources.

IDs are allocated deterministically per module and per resource type so that R.* constants
and the runtime lookup tables always agree.
"""
import os
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# module -> (res_dir, package, id_base, kotlin_out_dir)
MODULES = {
    "search": (f"{REPO}/search/src/main/res", "me.rerere.search", 0x7E000000, f"{REPO}/search/src/main/kotlin"),
    "app": (f"{REPO}/app/src/main/res", "me.rerere.rikkahub", 0x7F000000, f"{REPO}/desktop/src/main/kotlin"),
    "ui": (f"{REPO}/ui/src/main/res", "me.rerere.ui", 0x7D000000, f"{REPO}/ui/src/main/kotlin"),
    "oauth": (f"{REPO}/oauth/src/main/res", "me.rerere.oauth", 0x7C000000, f"{REPO}/oauth/src/main/kotlin"),
}

TYPE_OFFSET = {
    "string": 0x000000,
    "drawable": 0x400000,
    "color": 0x500000,
    "raw": 0x600000,
    "mipmap": 0x700000,
    "font": 0x800000,
}

ESCAPES = {
    "\\n": "\n", "\\t": "\t", "\\'": "'", '\\"': '"', "\\\\": "\\",
    "\\@": "@", "\\?": "?", "\\u0027": "'",
}


def unescape(text: str) -> str:
    out = text
    for k, v in ESCAPES.items():
        out = out.replace(k, v)
    return out


def kotlin_str(s: str) -> str:
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n").replace("\r", "")
    return '"' + out + '"'


def parse_strings(path: str) -> dict:
    result = {}
    if not os.path.exists(path):
        return result
    root = ET.parse(path).getroot()
    for child in root:
        if child.tag not in ("string", "plurals"):
            continue
        name = child.get("name")
        if not name:
            continue
        if child.tag == "string":
            result[name] = unescape("".join(child.itertext()))
        else:
            items = {}
            for item in child:
                q = item.get("quantity")
                if q:
                    items[q] = unescape("".join(item.itertext()))
            result[name] = items
    return result


def parse_colors(path: str) -> list:
    if not os.path.exists(path):
        return []
    root = ET.parse(path).getroot()
    return [c.get("name") for c in root if c.tag == "color" and c.get("name")]


def scan_res_dir(res_dir: str, prefix: str) -> dict:
    """stem -> relative path (files are flattened into res/drawable at packaging time)."""
    found = {}
    for entry in sorted(os.listdir(res_dir)):
        if not entry.startswith(prefix):
            continue
        d = os.path.join(res_dir, entry)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            stem, ext = os.path.splitext(f)
            found[stem] = "res/drawable/" + stem + ext
    return found


def main():
    for module, (res_dir, pkg, base, out_dir) in MODULES.items():
        default = parse_strings(os.path.join(res_dir, "values", "strings.xml"))
        if not default:
            print(f"{module}: no strings, skipped")
            continue

        names = sorted(default.keys())
        ids = {name: base + TYPE_OFFSET["string"] + i + 1 for i, name in enumerate(names)}

        # locale tables
        locales = {}
        for entry in sorted(os.listdir(res_dir)):
            if entry.startswith("values-"):
                lang = entry[len("values-"):]
                data = parse_strings(os.path.join(res_dir, entry, "strings.xml"))
                if data:
                    locales[lang] = data

        drawables = scan_res_dir(res_dir, "drawable")
        mipmaps = scan_res_dir(res_dir, "mipmap")
        fonts = scan_res_dir(res_dir, "font")
        colors = parse_colors(os.path.join(res_dir, "values", "colors.xml"))
        raws = scan_res_dir(res_dir, "raw")

        pkg_dir = os.path.join(out_dir, *pkg.split("."))
        os.makedirs(pkg_dir, exist_ok=True)

        # ---------- R.kt ----------
        r = [f"// Generated by tools/gen_resources.py from {os.path.relpath(res_dir, REPO)}", f"package {pkg}", "", "object R {"]

        def const_block(type_name, entries):
            r.append(f"    object {type_name} {{")
            for i, name in enumerate(entries):
                safe = name.replace(".", "_").replace("-", "_")
                r.append(f"        const val {safe} = {base + TYPE_OFFSET[type_name] + i + 1}")
            r.append("    }")

        const_block("string", names)
        const_block("drawable", sorted(drawables.keys()))
        const_block("mipmap", sorted(mipmaps.keys()))
        const_block("color", sorted(colors) if colors else [])
        const_block("raw", sorted(raws.keys()))
        const_block("font", sorted(fonts.keys()))
        r.append("}")
        open(os.path.join(pkg_dir, "R.kt"), "w").write("\n".join(r) + "\n")

        # ---------- RDrawableTable.kt (id -> packaged path) ----------
        table = ["// Generated by tools/gen_resources.py", f"package {pkg}", "",
                 "object RDrawableTable {", "    val byId: Map<Int, String> = mapOf("]
        for i, name in enumerate(sorted(drawables.keys())):
            table.append(f"        {base + TYPE_OFFSET['drawable'] + i + 1} to {kotlin_str(drawables[name])},")
        for i, name in enumerate(sorted(mipmaps.keys())):
            table.append(f"        {base + TYPE_OFFSET['mipmap'] + i + 1} to {kotlin_str(mipmaps[name])},")
        table.append("    )")
        table.append("}")
        open(os.path.join(pkg_dir, "RDrawableTable.kt"), "w").write("\n".join(table) + "\n")

        # ---------- RStringTable.kt (chunked + lazy to stay under the JVM 64KB method limit) ----------
        CHUNK = 200
        st = ["// Generated by tools/gen_resources.py", f"package {pkg}", "", "object RStringTable {"]

        def emit_map(prefix, entries):
            chunk_names = []
            for i in range(0, len(entries), CHUNK):
                cname = f"{prefix}Chunk{i // CHUNK}"
                st.append(f"    private val {cname}: Map<Int, String> by lazy {{ mapOf(")
                for k, v in entries[i:i + CHUNK]:
                    st.append(f"        {k} to {v},")
                st.append("    ) }")
                chunk_names.append(cname)
            if not chunk_names:
                st.append(f"    private val {prefix}ChunkEmpty: Map<Int, String> = emptyMap()")
                chunk_names.append(f"{prefix}ChunkEmpty")
            return chunk_names

        def entry_value(value):
            if isinstance(value, dict):
                return value.get("other") or next(iter(value.values()), "")
            return value

        default_entries = [(ids[n], kotlin_str(entry_value(default[n]))) for n in names]
        default_chunks = emit_map("default", default_entries)

        locale_chunks = {}
        for lang, data in locales.items():
            entries = [(ids[n], kotlin_str(entry_value(v))) for n, v in data.items() if n in ids]
            locale_chunks[lang] = emit_map("loc" + lang.replace("-", "_"), entries)

        st.append("")
        st.append("    val default: Map<Int, String> by lazy { " + " + ".join(default_chunks) + " }")
        st.append("")
        st.append("    val byLocale: Map<String, Map<Int, String>> by lazy {")
        st.append("        mapOf(")
        for lang, chunks in locale_chunks.items():
            st.append(f"            {kotlin_str(lang)} to (" + " + ".join(chunks) + "),")
        st.append("        )")
        st.append("    }")
        st.append("}")
        open(os.path.join(pkg_dir, "RStringTable.kt"), "w").write("\n".join(st) + "\n")

        print(f"{module}: {len(names)} strings, {len(locales)} locales, "
              f"{len(drawables)} drawables, {len(mipmaps)} mipmaps, {len(fonts)} fonts, {len(raws)} raw")


if __name__ == "__main__":
    main()
